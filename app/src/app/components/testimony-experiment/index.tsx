import { useState } from "react";
import { SOURCES, testimonyFor } from "../../data/tax-rebate-62f";
import { SourcesProvider } from "../ballot/sources-context";
import { Chapter } from "./frozen/Chapter";
import { SiteNav, useDeviceWidthViewport } from "./frozen/chrome";
import {
  TestimonyFeed,
  type StanceFilter,
  type TypeFilter,
} from "../tax-rebate-62f/testimony";

/**
 * The testimony feed on its own route, to be worked on without the rest of the
 * ballot page around it.
 *
 * The page shell is a snapshot: the nav and the Chapter it sits in live in
 * ./frozen, copied on the day this route was taken, so the surroundings do not
 * move when the ballot page does.
 *
 * The feed itself is not frozen, and should not be. A testimony card is the
 * same object wherever it appears, so it has one definition; two copies would
 * drift and the drift would be invisible until somebody noticed the two pages
 * disagreeing about what a statement looks like.
 */
export default function TestimonyExperiment() {
  const [stance, setStance] = useState<StanceFilter>("all");
  const [accountType, setAccountType] = useState<TypeFilter>("all");
  useDeviceWidthViewport();

  return (
    <SourcesProvider value={SOURCES}>
      <div className="bg-ground min-h-screen font-body text-ink overflow-x-clip">
        <SiteNav />
        {/* No contents bar here, so the only pinned thing is the nav, and the
            feed's own sticky bar clears that rather than the pair. */}
        <main className="mx-auto max-w-[1180px] px-[20px] sm:px-[32px] pt-[20px] sm:pt-[32px] pb-[140px] [--pinned-h:0px]">
          <Chapter
            id="testimony"
            question="What is the public saying?"
          >
            <TestimonyFeed
              filter={stance}
              onFilterChange={setStance}
              typeFilter={accountType}
              onTypeFilterChange={setAccountType}
              items={testimonyFor(() => true)}
              stickyTop="var(--pinned-h)"
              includeFollowingFilter
              includeTypeFilter
              asCards
            />
          </Chapter>
        </main>
        {/* Pinned to the bottom: the note has to stay visible without being
            the first thing on the page, and a footer that scrolls away is a
            note most readers never reach. */}
        <footer className="fixed bottom-0 left-0 right-0 z-40 bg-caution-soft border-t border-caution-ink/28">
          {/* Parked: the band above the bar, 8px of solid ground and 48px of
              fade, so content dissolved rather than cutting at the border.
          <div
            aria-hidden
            className="pointer-events-none absolute bottom-[calc(100%+1px)] left-0 right-0 h-[56px] bg-gradient-to-t from-ground from-14% via-ground/80 via-57% to-transparent"
          />
          */}
          <div className="px-[20px] sm:px-[32px] py-[28px]">
            <p className="font-body text-xs sm:text-sm text-caution-ink leading-[1.5]">
  Prototype for demo purposes only. All content displayed on this
                page was either generated by AI (for individuals) or gathered from
                published statements in public outlets (for orgs and gov
                officials) for MA 2026 ballot question 5.
            </p>
          </div>
        </footer>
      </div>
    </SourcesProvider>
  );
}
